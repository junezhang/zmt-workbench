/* ---------- 标题 ---------- */
function makeTitles(core, angle, seed) {
  const r = rng(seed + angle);
  const c = core.replace(/[，。！？,.!?]/g, '');
  const short = c.length > 14 ? c.slice(0, 14) : c;
  const pool = [
    `${short}火了，我看到的是另一层`,
    `一个设计师眼里的${short}`,
    `从${short}说起，聊聊一个老问题`,
    `${short}这件事，很多人看错了方向`,
    `热闹之外，${short}还剩下什么`,
    `${short}背后，藏着一个更值钱的问题`,
    `我为什么对${short}有点不同看法`,
    `${short}，和我做设计时踩过的那个坑`
  ];
  const out = [];
  while (out.length < 5 && out.length < pool.length) {
    const t = pick(pool, r);
    if (!out.includes(t)) out.push(t);
  }
  return out;
}

/* ---------- 正文 ---------- */
function makeBody(topic, angle, seed) {
  const core = topic.title || '这个话题';
  const plat = topic.platform || '热榜';
  const sum = topic.summary || '';
  const src = (topic.source && topic.source.name) || '';
  const r = rng(seed + angle + core);

  const L = [];
  L.push(pick(P.hook, r)(core, plat));
  L.push('');
  if (sum) L.push(sum + (src ? `（来源：${src}）` : ''));
  L.push('');
  L.push(pick(P.turn, r));
  L.push('');

  L.push('【事情的前因后果】');
  L.push('');
  L.push(pick(P.bgLead, r));
  L.push('');
  const facts = sum.split(/[。；]/).map(s => s.trim()).filter(s => s.length > 6).slice(0, 4);
  if (facts.length) facts.forEach((f, i) => L.push(`${i + 1}. ${f}。`));
  else L.push(`1. ${core}。`);
  L.push('');
  if (topic.angle) L.push(topic.angle);
  L.push(pick(P.bgTail, r));
  L.push('');

  L.push('【一个设计师的看法】');
  L.push('');
  const views = P.view[angle] || P.view['设计方法'];
  views.forEach(v => {
    L.push(v.h);
    L.push(v.b(core));
    L.push('');
  });

  const g = pick(P.golden[angle] || P.golden['设计方法'], r);
  L.push('【最后一句】');
  L.push('');
  L.push(g);
  L.push('');
  L.push(pick(P.end, r)(core));

  return { text: L.join('\n'), golden: g };
}

/* ---------- 对外主函数 ---------- */
function buildArticle(topic, opts) {
  opts = opts || {};
  const angle = opts.angle || '行业趋势';
  const seed = opts.seed || '0';
  const usePre = opts.usePre !== false;

  if (usePre && topic.article && topic.article.body && topic.article.body.length > 200) {
    return {
      titles: topic.article.titles && topic.article.titles.length ? topic.article.titles : makeTitles(topic.title, angle, seed),
      body: topic.article.body,
      golden: topic.article.golden || '',
      mode: '当日精写稿'
    };
  }
  const b = makeBody(topic, angle, seed);
  return {
    titles: makeTitles(topic.title, angle, seed),
    body: b.text,
    golden: b.golden,
    mode: angle + ' · 自动成稿'
  };
}

